// ============================================================
// Writes what the dcb-notation skill (skills/dcb-notation/) carries of
// the playground, so it works when copied out of this repository:
//
//   references/language.md      – `sourceLanguageReference` (dsl.js),
//                                 the reference held to the parser by
//                                 dsl.test.js, under a note translating
//                                 its tool names to the skill's commands;
//   scripts/playground-core.js  – model.js, evaluate.js and dsl.js as
//                                 one script, which scripts/dcb.js runs.
//
// Copied rather than linked because a skill is installed by copying its
// folder, and rather than fetched from dcb.events because the hosted
// playground may be pinned to another major of the language.
//
// Run with `node app/generate-skill.js` after changing any of those
// three files. Nothing here runs in the browser.
// ============================================================
const fs = require('fs');
const path = require('path');
const { createSandbox, loadApp } = require('./test-harness.js');

const APP = __dirname;
const SKILL = path.join(APP, '..', 'skills', 'dcb-notation');

const { sandbox } = createSandbox();
loadApp(sandbox, ['model.js', 'evaluate.js', 'dsl.js'], {
  trailer: 'globalThis.MODEL_VERSION = MODEL_VERSION;',
});

const NOTE = `<!-- Generated by app/generate-skill.js from dsl.js – regenerate, never hand-edit. -->

> Language version ${sandbox.MODEL_VERSION}. This reference is also served to the playground's own
> tools, and names them. Here, \`start_model\` and \`apply_model_source\` are \`dcb.js check\`,
> \`get_model_source\` is \`dcb.js print\` and \`derive_boundary\` is the boundary \`check\` prints;
> \`allowRemovals\` has no counterpart, since your file is the whole model.
> A scenario without \`then\` is not recorded: \`check\` reports what the model does instead.
> Advisories are problems too: \`check\` exits 1 on them.
> "Not offered" constructs are the experimental ones, which \`check\` always refuses.

`;

const CORE_HEADER = `// Generated by app/generate-skill.js from model.js, evaluate.js and dsl.js – regenerate, never hand-edit.
// One classic script, run by dcb.js in a vm context.
`;

fs.writeFileSync(path.join(SKILL, 'references', 'language.md'), NOTE + sandbox.sourceLanguageReference());
fs.writeFileSync(path.join(SKILL, 'scripts', 'playground-core.js'), CORE_HEADER + ['model.js', 'evaluate.js', 'dsl.js']
  .map((file) => fs.readFileSync(path.join(APP, file), 'utf8'))
  .join('\n;\n'));
console.log('wrote skills/dcb-notation/references/language.md and scripts/playground-core.js');
